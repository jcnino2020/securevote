CREATE TABLE IF NOT EXISTS election_metadata (
 election_id INT UNSIGNED PRIMARY KEY, organization VARCHAR(100) NOT NULL DEFAULT '', department VARCHAR(100) NOT NULL DEFAULT '', school_year VARCHAR(30) NOT NULL DEFAULT '',
 FOREIGN KEY(election_id) REFERENCES elections(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS election_forum (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, election_id INT UNSIGNED NOT NULL, kind ENUM('event','video','material') NOT NULL, title VARCHAR(150) NOT NULL, description TEXT NOT NULL, resource_url VARCHAR(2000) NOT NULL DEFAULT '', event_at DATETIME NULL, status ENUM('draft','published','withdrawn') NOT NULL DEFAULT 'draft', updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(election_id) REFERENCES elections(id) ON DELETE CASCADE, KEY idx_forum (election_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS election_snapshots (
 election_id INT UNSIGNED PRIMARY KEY, content LONGTEXT NOT NULL, FOREIGN KEY(election_id) REFERENCES elections(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS election_changes (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, election_id INT UNSIGNED NOT NULL, summary VARCHAR(1000) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(election_id) REFERENCES elections(id) ON DELETE CASCADE, KEY idx_changes(election_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS password_resets (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL, token_hash CHAR(64) NOT NULL UNIQUE, expires_at DATETIME NOT NULL, used_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE, KEY idx_reset_user(user_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS account_security (
 user_id INT UNSIGNED PRIMARY KEY, session_version CHAR(32) NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

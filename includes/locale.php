function sv_language(): string
{
    if (isset($_GET['lang']) && in_array($_GET['lang'], ['en', 'fil'], true)) {
        $_SESSION['language'] = $_GET['lang'];
    }
    return ($_SESSION['language'] ?? 'en') === 'fil' ? 'fil' : 'en';
}


/**
 * Render one icon.
 *
 * @param string $name  key from sv_icon_paths()
 * @param int    $size  pixel size of the square
 * @param string $class extra CSS classes
 */
function sv_icon(string $name, int $size = 20, string $class = ''): string
{
    $icons = sv_icon_paths();

    if (!isset($icons[$name])) {
        $name = 'info';
    }

    $size    = max(12, min(64, $size));
    $classes = 'sv-icon' . ($class !== '' ? ' ' . $class : '');
    $attrs   = 'class="' . e($classes) . '" width="' . $size . '" height="' . $size . '" viewBox="0 0 24 24" fill="none"'
        . ' stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"'
        . ' aria-hidden="true" focusable="false"';

    return '<svg ' . $attrs . '>' . $icons[$name] . '</svg>';
}

